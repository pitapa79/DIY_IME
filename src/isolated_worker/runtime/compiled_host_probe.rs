use super::{Api, Bytes, Limits, P, Recorder, Runtime, create_engine};
use std::{ffi::CStr, ptr};

pub(in crate::isolated_worker) const OFFICIAL_WASM_HASH: &str =
    "105c0ceb2854dba27a747eae5faa6e393bb99a88ce5ab3048a468fa9add88134";
const MAX_ARTIFACT_BYTES: usize = 8 * 1024 * 1024;

pub(super) fn compile(api: &Api, limits: &Limits, wasm: &[u8]) -> Result<Vec<u8>, String> {
    if digest(wasm)? != OFFICIAL_WASM_HASH {
        return Err("unsupported probe module".into());
    }
    // Resolve before allocating engine resources. The DLL is already verified.
    let serialize: unsafe extern "C" fn(P, *mut Bytes) -> P =
        unsafe { symbol(api, c"wasmtime_module_serialize")? };
    let engine = create_engine(api, limits)?;
    let mut module = ptr::null_mut();
    // SAFETY: exact signatures from the pinned C API; all owned handles and
    // vectors are released before returning. No Store or guest is created.
    unsafe {
        let result = (|| {
            api.check(
                (api.module_new)(engine, wasm.as_ptr(), wasm.len(), &mut module),
                ptr::null_mut(),
            )?;
            let mut bytes = Bytes {
                size: 0,
                data: ptr::null_mut(),
            };
            api.check(serialize(module, &mut bytes), ptr::null_mut())?;
            let result = if bytes.data.is_null() || !(1..=MAX_ARTIFACT_BYTES).contains(&bytes.size)
            {
                Err("probe artifact exceeds bound".into())
            } else {
                Ok(std::slice::from_raw_parts(bytes.data, bytes.size).to_vec())
            };
            (api.bytes_delete)(&mut bytes);
            result
        })();
        if !module.is_null() {
            (api.module_delete)(module);
        }
        (api.engine_delete)(engine);
        result
    }
}

pub(super) fn load<'a>(
    api: &'a Api,
    limits: &Limits,
    diagnostics: Option<&'a Recorder>,
    artifact: &[u8],
    expected: &str,
) -> Result<Runtime<'a>, String> {
    if !(1..=MAX_ARTIFACT_BYTES).contains(&artifact.len()) || digest(artifact)? != expected {
        return Err("compiled bytes changed".into());
    }
    Runtime::with_module(api, limits, diagnostics, |engine, module| {
        // SAFETY: the trusted Parent supplies a read-only asset generated by
        // its compile-only process from the fixed module with this same DLL
        // and engine settings. The digest is checked before deserialization.
        unsafe {
            let deserialize: unsafe extern "C" fn(P, *const u8, usize, *mut P) -> P =
                symbol(api, c"wasmtime_module_deserialize")?;
            api.check(
                deserialize(engine, artifact.as_ptr(), artifact.len(), module),
                ptr::null_mut(),
            )
        }
    })
}

fn digest(bytes: &[u8]) -> Result<String, String> {
    crate::isolated_worker::adapter::sha256(bytes).map_err(|_| "probe SHA-256 failed".into())
}

unsafe fn symbol<T: Copy>(api: &Api, name: &CStr) -> Result<T, String> {
    let pointer = unsafe { super::GetProcAddress(api._library.0, name.as_ptr().cast()) };
    if pointer.is_null() || std::mem::size_of::<T>() != std::mem::size_of_val(&pointer) {
        return Err("probe API unavailable".into());
    }
    // SAFETY: callers select the exact export signature from the pinned C API.
    Ok(unsafe { std::mem::transmute_copy(&pointer) })
}
